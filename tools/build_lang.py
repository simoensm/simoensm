#!/usr/bin/env python3
"""Build the French and Dutch addresses of the site (fr/index.html, nl/index.html).

index.html stays the single source. Run this after every change to it:
    python3 tools/build_lang.py
The copies load every file from the root through <base href="../">, force their
language, and carry their own title, description, canonical and hreflang tags.
"""
import pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SITE = "https://mathias-simoens.abovebelgium.be/"
META = {
    "fr": {
        "title": "Mathias Simoens · Ingénieur de gestion, data et photographie",
        "desc": "Mathias Simoens, étudiant en master Ingénieur de gestion (Business Analytics) à l'UCLouvain, Belgique. Data, machine learning, projets logiciels, et le travail photo et vidéo d'Above Belgium.",
        "locale": "fr_BE",
    },
    "nl": {
        "title": "Mathias Simoens · Handelsingenieur, data en fotografie",
        "desc": "Mathias Simoens, masterstudent Handelsingenieur (Business Analytics) aan UCLouvain, België. Data, machine learning, softwareprojecten, en het foto- en videowerk van Above Belgium.",
        "locale": "nl_BE",
    },
}


def build(lang, src):
    m = META[lang]
    s = src
    s = s.replace('<html lang="en">', f'<html lang="{lang}" data-lang="{lang}">', 1)
    s = s.replace('<meta charset="utf-8">', '<meta charset="utf-8">\n<base href="../">', 1)
    s = re.sub(r"<title>.*?</title>", f"<title>{m['title']}</title>", s, count=1)
    for attr in ('name="description"', 'property="og:description"', 'name="twitter:description"'):
        s = re.sub(rf'(<meta {attr} content=")[^"]*', lambda x: x.group(1) + m["desc"], s, count=1)
    s = s.replace(f'<link rel="canonical" href="{SITE}">', f'<link rel="canonical" href="{SITE}{lang}/">', 1)
    s = s.replace(f'<meta property="og:url" content="{SITE}">',
                  f'<meta property="og:url" content="{SITE}{lang}/">\n<meta property="og:locale" content="{m["locale"]}">', 1)
    s = s.replace('"inLanguage":"en"', f'"inLanguage":"{lang}"', 1)
    # fragment links must stay on this page, not jump to the root through <base>
    s = s.replace('href="#', f'href="/{lang}/#').replace("url(#", f"url(/{lang}/#")
    head, rest = s.split('\n', 1)
    return head + "\n<!-- Generated by tools/build_lang.py from index.html. Do not edit by hand. -->\n" + rest


def main():
    src = (ROOT / "index.html").read_text(encoding="utf-8")
    for lang in META:
        out = ROOT / lang / "index.html"
        out.parent.mkdir(exist_ok=True)
        out.write_text(build(lang, src), encoding="utf-8")
        print("wrote", out.relative_to(ROOT))


if __name__ == "__main__":
    main()
